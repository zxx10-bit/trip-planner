# 通用到无法体现「本地特色」的菜系键:识别到这些时优先使用城市菜单
GENERIC_CUISINE_KEYS = {"中餐厅", "家常菜", "地方菜", "快餐", "融合菜", "私房菜"}


def normalize_cuisine(cuisine: str) -> Optional[str]:
    """从高德 type/名称文本中识别菜系关键词

    Args:
        cuisine: 形如 "餐饮服务;中餐厅;北京菜" 的高德类型文本

    Returns:
        识别到的菜系键;未识别或只匹配到通用类型时返回 None
    """
    if not cuisine:
        return None
    text = str(cuisine)
    for keyword in CUISINE_KEYWORDS:
        if keyword in text and keyword not in GENERIC_CUISINE_KEYS:
            return keyword
    return None


def signature_dishes(city: str, cuisine: str, venue_name: str, seed: int = 0) -> List[str]:
    """生成 3-4 道招牌菜

    优先使用菜系专属菜单,其次使用城市菜单,最后使用通用兜底菜单。
    相同输入始终返回相同结果;seed 仅用于在同样优质的候选间做稳定轮换。

    Args:
        city: 城市名称
        cuisine: 高德 type 文本或菜系关键词
        venue_name: 店名(用于派生稳定的轮换偏移)
        seed: 额外种子,用于稳定地打散顺序

    Returns:
        3-4 道真实存在的中文招牌菜
    """
    try:
        dish_source: Optional[List[str]] = None
        cuisine_key = normalize_cuisine(cuisine)
        if not cuisine_key and cuisine:
            # 允许直接传入 "火锅" 这类菜系词
            for keyword in CUISINE_KEYWORDS:
                if keyword in str(cuisine):
                    cuisine_key = keyword
                    break

        if cuisine_key:
            dish_source = CUISINE_DISHES.get(cuisine_key)

        if not dish_source and city:
            dish_source = CITY_DISHES.get(str(city).strip())

        if not dish_source:
            dish_source = GENERIC_DISHES

        dishes = [d for d in dish_source if d]
        if not dishes:
            dishes = list(GENERIC_DISHES)

        # 使用店名与 seed 生成稳定的偏移量
        base = sum(ord(ch) for ch in str(venue_name or "")) + int(seed or 0)
        offset = base % len(dishes)

        count = min(4, len(dishes)) if len(dishes) >= 4 else len(dishes)
        count = max(3, count) if len(dishes) >= 3 else len(dishes)

        rotated = [dishes[(offset + i) % len(dishes)] for i in range(count)]
        # 去重并保持顺序
        seen = set()
        result: List[str] = []
        for dish in rotated:
            if dish not in seen:
                seen.add(dish)
                result.append(dish)

        # 数量不足时从原始菜单补齐
        for dish in dishes:
            if len(result) >= min(3, len(dishes)):
                break
            if dish not in seen:
                seen.add(dish)
                result.append(dish)

        return result
    except Exception:
        return list(GENERIC_DISHES)


def city_dishes(city: str) -> List[str]:
    """获取某城市的招牌菜列表(不存在时返回通用菜单)"""
    return list(CITY_DISHES.get(str(city or "").strip(), GENERIC_DISHES))


def taste_keywords(free_text: str) -> List[str]:
    """从用户自由文本中提取口味偏好对应的关键词

    Args:
        free_text: 用户额外要求文本

    Returns:
        匹配到的关键词列表
    """
    keywords: List[str] = []
    if not free_text:
        return keywords
    text = str(free_text)
    for taste, words in TASTE_KEYWORDS.items():
        if taste in text:
            keywords.extend(words)
    # 去重
    seen = set()
    result: List[str] = []
    for word in keywords:
        if word not in seen:
            seen.add(word)
            result.append(word)
    return result
